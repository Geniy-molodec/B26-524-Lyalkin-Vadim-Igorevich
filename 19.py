import re
def find_phones(text):
    return [m.group() for m in phone_re.finditer(text)]

phone_re = re.compile(
    r"(?<![\w+])"
    r"(?:\+7|8)"
    r"\s"
    r"(?:\(\d{3}\)|\d{3})"
    r"\s"
    r"\d{3}-\d{2}-\d{2}"
    r"(?!\d)"
)


text = """\
Мой номер +7 999 123-45-67.
Звоните 8 (912) 345-67-89, не стесняйтесь!
Контакты: +7 (495) 111-22-33; 8 800 555-35-35; +7 900 000-00-00.
Номер в скобках (+7 999 123-45-67) тоже виден.
Номер в кавычках: «8 999 123-45-67».
Первый:8 999 123-45-67
Подряд через запятую: 8 999 111-11-11,8 999 222-22-22
+7 999 123-45-67
8 (999) 765-43-21

Мало цифр в коде: 8 99 123-45-67
Неверная разбивка: +7 999 1234-5-67
Слишком длинный хвост: 8 999 123-45-678
Лишняя цифра в начале: 18 999 123-45-67
Другой код страны: +8 999 123-45-67 и +17 999 123-45-67
Без пробелов: +79991234567 и 89991234567
Пробелы вместо дефисов: 8 999 123 45 67
Несбалансированные скобки: 8 (999 123-45-67 и 8 999) 123-45-67
Просто числа: 12345, 2026-09-23, 192.168.1.10
Буква прилипла: abc8 999 123-45-67
"""
for phone in find_phones(text):
    print(phone)