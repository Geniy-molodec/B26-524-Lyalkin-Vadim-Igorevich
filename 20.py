import re

text = """Встречи состоятся 15.09.2026, 21.09.2026 и 03.10.2026.
Следующая встреча запланирована на 1.11.2026."""

date_re = re.compile(
    r"(?<!\d)"
    r"(?:0[1-9]|[12]\d|3[01])\."
    r"(?:0[1-9]|1[0-2])\."
    r"\d{4}"
    r"(?!\d)"
)

for date in date_re.findall(text):
    print(date)