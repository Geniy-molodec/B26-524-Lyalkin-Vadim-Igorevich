import re

def normalize_spaces(text):
    return re.sub(r" {2,}", " ", text).strip()

TESTS = [
    # из условия
    "Это   строка    с     большим    количеством   пробелов.",
    "   Текст   с   пробелами   ",

    # уже нормальные строки
    "Уже нормальная строка",
    "Одно слово",
    "a b c d",

    # пробелы только в начале или только в конце
    "   слева",
    "справа   ",
    " один пробел по краям ",

    # пробелы между словами
    "два  пробела",
    "много                     пробелов",
    "a  b   c    d     e",

    # знаки препинания
    "Привет  ,   мир  !",
    "Скобки  (  внутри  )  текста",

    # только пробелы и пустая строка
    "     ",
    " ",
    "",

    # табуляции и переводы строк (обычный пробел их не трогает)
    "Табуляция\t\tмежду",
    "Первая   строка\nВторая   строка",
    "  \n  начало с переноса",

    # неразрывный пробел (не равен обычному)
    "слово\u00a0\u00a0слово",

    # юникод и цифры
    "Привет   мир   123   😀",
    "2026   09   23",
]

for src in TESTS:
    print(normalize_spaces(src))